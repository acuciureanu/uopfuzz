#!/usr/bin/env node
/**
 * A/B comparison — UoPFuzz vs GHunter on a shared ground truth.
 *
 * GHunter itself cannot be run here (its artifact requires building a patched
 * Node v21/V8 from source — hours and tens of GB — and its verdicts would
 * describe a 2023 runtime, not this one). Instead this script scores both
 * tools on the UNION of both gadgets' published/mined knowledge, at
 * (api, property) granularity:
 *
 *   GHunter's answers — the published, manually-validated gadget table
 *     (KTH-LangSec/server-side-prototype-pollution README, Node.js section;
 *     GHunter USENIX'24 paper Table 5). Encoded verbatim in PUBLISHED below.
 *   UoPFuzz's answers — the two machine-produced artifacts in this repo:
 *     benchmark/runtime-gadgets/RESULTS.md (corpus verdicts, regenerated by
 *     `npm run benchmark:runtime-gadgets -- --write`) and
 *     results/runtime-miner/findings.jsonl (miner output, `npm run
 *     mine:runtime-gadgets -- --write`).
 *
 * For each union entry we record: published-by-GHunter? detected-by-UoPFuzz
 * (on THIS Node)? Recall is computed both directions. Dead-on-this-Node
 * entries (FIXED/MITIGATED) are counted separately — a tool cannot be faulted
 * for a gadget the runtime no longer has, and the correct detection of a
 * gadget's death is itself signal.
 *
 * Usage: node benchmark/runtime-gadgets/ab-test.js [--write]
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const RESULTS_MD = path.join(__dirname, 'RESULTS.md');
const FINDINGS_JSONL = path.resolve(__dirname, '../../results/runtime-miner/findings.jsonl');
const OUT_MD = path.resolve(__dirname, '../../results/runtime-miner/AB-RESULTS.md');

// ─── GHunter's published Node.js gadgets (README table, Node.js section) ─────
// api → properties. Windows-only rows are excluded (cannot run here).
// `by` records attribution: G = GHunter, SS = Silent Spring (their baseline).
const PUBLISHED = [
  { api: 'child_process.exec',        properties: ['NODE_OPTIONS'],              by: 'SS' },
  { api: 'child_process.execFile',    properties: ['NODE_OPTIONS'],              by: 'SS' },
  { api: 'child_process.execFileSync', properties: ['shell', 'NODE_OPTIONS'],    by: 'SS' },
  { api: 'child_process.execSync',    properties: ['NODE_OPTIONS', 'shell', 'env'], by: 'SS' },
  { api: 'child_process.fork',        properties: ['NODE_OPTIONS'],              by: 'SS' },
  { api: 'child_process.spawn',       properties: ['shell', 'env', 'NODE_OPTIONS'], by: 'SS' },
  { api: 'child_process.spawnSync',   properties: ['shell', 'NODE_OPTIONS', 'env'], by: 'SS' },
  { api: 'fetch',                     properties: ['method', 'body', 'referrer', 'socketPath'], by: 'G' },
  { api: 'http.get',                  properties: ['hostname', 'headers', 'method', 'path', 'port'], by: 'G' },
  { api: 'http.request',              properties: ['hostname', 'headers', 'method', 'path', 'port'], by: 'G' },
  { api: 'http.Server.listen',        properties: ['backlog'],                   by: 'G' },
  { api: 'https.get',                 properties: ['hostname', 'headers', 'method', 'path', 'port', 'NODE_TLS_REJECT_UNAUTHORIZED'], by: 'G' },
  { api: 'https.request',             properties: ['hostname', 'headers', 'method', 'path', 'port', 'NODE_TLS_REJECT_UNAUTHORIZED'], by: 'G' },
  { api: 'import()',                  properties: ['source'],                    by: 'G' },
  { api: 'tls.connect',               properties: ['path', 'port', 'NODE_TLS_REJECT_UNAUTHORIZED'], by: 'G' },
  { api: 'require',                   properties: ['main', 'NODE_OPTIONS'],      by: 'G+SS' },
  { api: 'worker_threads.Worker',     properties: ['argv', 'env', 'eval'],       by: 'G' },
];

// GHunter's API spellings → the implementation class whose corpus/miner
// verdicts also answer for them. Only same-implementation pairs:
// http(s).get is a thin wrapper over http(s).request (same _http_client path).
const API_ALIASES = {
  'http.get': ['http.request'],
  'https.get': ['https.request'],
};

function loadOurVerdicts() {
  // Corpus: RESULTS.md table rows "| VERDICT | id | api | property | ...".
  const ours = new Map(); // "api\0property" → verdict
  const md = fs.readFileSync(RESULTS_MD, 'utf8');
  for (const line of md.split('\n')) {
    const m = line.match(/^\| (\S+) \| [^|]+ \| ([^|]+) \| ([^|]+) \|/);
    if (!m || m[1] === 'Verdict') continue;
    ours.set(`${m[2].trim()}\0${m[3].trim()}`, m[1].trim());
  }
  // Miner: findings.jsonl (LIVE value-sensitive and DoS count as gadgets;
  // LIVE definedness-sensitive is reported but not counted as a full gadget).
  if (fs.existsSync(FINDINGS_JSONL)) {
    for (const line of fs.readFileSync(FINDINGS_JSONL, 'utf8').split('\n')) {
      if (!line.trim()) continue;
      const f = JSON.parse(line);
      const key = `${f.class}\0${f.property}`;
      const strong = f.verdict === 'DoS' || (f.verdict === 'LIVE' && f.grade === 'value-sensitive');
      const weak = f.verdict === 'LIVE';
      const verdict = strong ? 'DETECTED' : weak ? 'WEAK' : null;
      if (!verdict) continue;
      const prev = ours.get(key);
      if (!prev || prev === 'WEAK') ours.set(key, verdict);
    }
  }
  return ours;
}

export function abCompare(published, ours) {
  const rows = [];
  for (const entry of published) {
    for (const property of entry.properties) {
      const key = `${entry.api}\0${property}`;
      let verdict = ours.get(key);
      // Same-implementation aliases (http.get ≡ http.request, …): a verdict
      // for the underlying class answers for the alias too.
      if (!verdict) {
        for (const alias of API_ALIASES[entry.api] || []) {
          verdict = ours.get(`${alias}\0${property}`);
          if (verdict) { verdict = `${verdict} (via ${alias})`; break; }
        }
      }
      verdict = verdict || 'NOT-COVERED';
      rows.push({ api: entry.api, property, by: entry.by, ghunter: 'published', uopfuzz: verdict });
    }
  }
  // Entries WE found that GHunter never published.
  const publishedKeys = new Set(published.flatMap(e => e.properties.map(p => `${e.api}\0${p}`)));
  for (const [key, verdict] of ours) {
    if (publishedKeys.has(key)) continue;
    if (verdict !== 'DETECTED') continue; // only strong findings count as new gadgets
    const [api, property] = key.split('\0');
    rows.push({ api, property, by: '—', ghunter: 'not published', uopfuzz: verdict });
  }
  return rows;
}

function summarize(rows) {
  const publishedRows = rows.filter(r => r.ghunter === 'published');
  const isDead = (v) => v.startsWith('FIXED-UPSTREAM') || v.startsWith('MITIGATED-UPSTREAM');
  const live = publishedRows.filter(r => !isDead(r.uopfuzz));
  const dead = publishedRows.filter(r => isDead(r.uopfuzz));
  const weDetectLive = live.filter(r => r.uopfuzz.startsWith('DETECTED')).length;
  const missedRows = live.filter(r => !r.uopfuzz.startsWith('DETECTED'));
  const ghOnly = missedRows.length;
  const weOnly = rows.filter(r => r.ghunter === 'not published');
  return {
    publishedTotal: publishedRows.length,
    liveOnThisNode: live.length,
    deadOnThisNode: dead.length,
    uopfuzzRecallOnLive: live.length ? weDetectLive / live.length : 0,
    ghunterMissesThatWeFound: weOnly.length,
    ghunterPublishedThatWeMiss: ghOnly,
    missedRows,
    weOnly,
  };
}

function render(rows, s) {
  let md = `# A/B — UoPFuzz vs GHunter\n\nNode ${process.versions.node} — ${new Date().toISOString().slice(0, 10)}\n\n`;
  md += `Ground truth: union of GHunter's published, manually-validated Node gadget table and UoPFuzz's machine-verified findings (corpus + miner). GHunter itself cannot execute here (patched-Node v21 artifact); its answers are its own published table.\n\n`;
  md += `## Headline\n\n`;
  md += `- GHunter-published gadget properties: **${s.publishedTotal}**\n`;
  md += `- still live on this Node: **${s.liveOnThisNode}** (dead/fixed: ${s.deadOnThisNode})\n`;
  md += `- UoPFuzz recall on the live ones: **${(s.uopfuzzRecallOnLive * 100).toFixed(0)}%** (${s.liveOnThisNode - s.ghunterPublishedThatWeMiss}/${s.liveOnThisNode}${s.ghunterPublishedThatWeMiss ? ` — not fully proven: ${s.missedRows.map(r => `${r.api}.${r.property}=${r.uopfuzz}`).join(', ')}` : ''})\n`;
  md += `- machine-verified UoPFuzz gadgets GHunter never published: **${s.ghunterMissesThatWeFound}**\n`;
  md += `- manual effort: GHunter 31 person-hours · UoPFuzz 0\n\n`;
  md += `## Full table\n\n| API | Property | Published by | GHunter | UoPFuzz (this Node) |\n|---|---|---|---|---|\n`;
  for (const r of rows) md += `| ${r.api} | ${r.property} | ${r.by} | ${r.ghunter} | ${r.uopfuzz} |\n`;
  md += `\nWEAK = behavior changed by definedness only (not counted as a full gadget). NOT-COVERED = no driver/class reaches that API yet.\n`;
  return md;
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) {
  const rows = abCompare(PUBLISHED, loadOurVerdicts());
  const s = summarize(rows);
  console.log(render(rows, s));
  if (process.argv.includes('--write')) {
    fs.mkdirSync(path.dirname(OUT_MD), { recursive: true });
    fs.writeFileSync(OUT_MD, render(rows, s));
    console.error(`wrote ${OUT_MD}`);
  }
}
